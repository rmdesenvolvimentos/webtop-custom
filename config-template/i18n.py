#!/usr/bin/env python3
# =============================================================================
# i18n.py – Módulo de internacionalização para Cloud Desktop
# =============================================================================
# Uso em qualquer script Python do projeto:
#
#   from i18n import t, get_lang
#   print(t('save'))           # → "Salvar" (se PT-BR)
#   print(t('save'))           # → "Save" (se EN)
# =============================================================================
import os

_LANG_FILE = os.path.expanduser('~/.language_preference')

def get_lang() -> str:
    """Retorna o código de idioma ativo (ex: 'pt_BR')."""
    if os.path.exists(_LANG_FILE):
        code = open(_LANG_FILE).read().strip()
        if code in TRANSLATIONS:
            return code
    env = os.environ.get('LANG', 'pt_BR.UTF-8').split('.')[0]
    return env if env in TRANSLATIONS else 'pt_BR'


def t(key: str, **kwargs) -> str:
    """Retorna a tradução da chave no idioma atual."""
    lang = get_lang()
    text = TRANSLATIONS.get(lang, TRANSLATIONS['pt_BR']).get(key) \
        or TRANSLATIONS['pt_BR'].get(key) \
        or key
    return text.format(**kwargs) if kwargs else text


