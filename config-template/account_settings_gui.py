PROFILE_PATH = "/config/user_profile.json"
HTPASSWD_PATH = "/etc/nginx/.htpasswd"

def read_htpasswd():
    if not os.path.exists(HTPASSWD_PATH):
        return []
    try:
        with open(HTPASSWD_PATH, "r") as f:
            return f.readlines()
    except Exception:
        res = subprocess.run(["sudo", "cat", HTPASSWD_PATH], capture_output=True, text=True, check=False)
        return res.stdout.splitlines(keepends=True)

def write_htpasswd(content_str):
    try:
        with open(HTPASSWD_PATH, "w") as f:
            f.write(content_str)
            return
    except Exception:
        pass
    # Se der erro de permissão, ajusta permissões via sudo e grava via sudo tee
    subprocess.run(["sudo", "chown", "abc:abc", HTPASSWD_PATH], check=False)
    subprocess.run(["sudo", "chmod", "664", HTPASSWD_PATH], check=False)
    try:
        with open(HTPASSWD_PATH, "w") as f:
            f.write(content_str)
            return
    except Exception:
        p = subprocess.Popen(["sudo", "tee", HTPASSWD_PATH], stdin=subprocess.PIPE, stdout=subprocess.DEVNULL)
        p.communicate(content_str.encode())

def get_profile():
    p = {"username": os.environ.get("CUSTOM_USER", "Admin"), "displayName": os.environ.get("CUSTOM_USER", "Admin"), "hostname": "cloud-vps", "idleTimeoutMinutes": 15}
    if os.path.exists(PROFILE_PATH):
        try:
            with open(PROFILE_PATH) as f:
                p.update(json.load(f))
        except Exception:
            pass
    return p

def save_credentials(username, password, display_name, timeout_minutes, hostname="cloud-vps"):
    clean_user = username.strip().replace(" ", "_").lower()
    disp = display_name.strip() if display_name else username
    clean_host = re.sub(r'[^a-zA-Z0-9-]', '', (hostname or "cloud-vps").strip().replace(" ", "-")).lower() or "cloud-vps"

    if password:
        # Use OpenSSL SHA-512 crypt (-6)
        res = subprocess.run(["openssl", "passwd", "-6", password], capture_output=True, text=True)
        hashed = res.stdout.strip()
        write_htpasswd(f"{username}:{hashed}\n")
        
        # Update system Linux password for abc / sudo
        try:
            p = subprocess.Popen(["sudo", "chpasswd"], stdin=subprocess.PIPE)
            p.communicate(f"abc:{password}\n".encode())
        except Exception as e:
            print(f"Error setting system password: {e}")
    else:
        lines = read_htpasswd()
        new_lines = []
        for line in lines:
            if ":" in line:
                _, h = line.strip().split(":", 1)
                new_lines.append(f"{username}:{h}\n")
        if not new_lines:
            new_lines = [f"{username}:\n"]
        write_htpasswd("".join(new_lines))

    # Update system GECOS full name in /etc/passwd
    try:
        subprocess.run(["sudo", "usermod", "-c", disp, "abc"], check=False)
    except Exception as e:
        print(f"Error setting GECOS: {e}")

    # Update system Hostname in /etc/hosts & runtime & /etc/hostname
    try:
        with open("/etc/hosts") as hf:
            content = hf.read()
        if clean_host not in content:
            subprocess.run(f'echo "127.0.0.1 {clean_host}" | sudo tee -a /etc/hosts', shell=True, check=False)
        subprocess.run(["sudo", "hostname", clean_host], check=False)
        subprocess.run(f'echo "{clean_host}" | sudo tee /etc/hostname', shell=True, check=False)
    except Exception as e:
        print(f"Error setting hostname: {e}")

    # Update custom prompt configuration for terminal (so abc never appears)
    prompt_conf = f"""# Custom terminal identity generated by Account Settings GUI
export USER="{clean_user}"
export CUSTOM_USER="{clean_user}"
export CUSTOM_DISPLAY="{disp}"
export CUSTOM_HOST="{clean_host}"
PS1='\\[\\033[01;32m\\]{clean_user}@{clean_host}\\[\\033[00m\\]:\\[\\033[01;34m\\]\\w\\[\\033[00m\\]\\$ '
"""
    try:
        with open("/config/.custom_prompt_env", "w") as f:
            f.write(prompt_conf)
    except Exception as e:
        print(f"Error saving prompt env: {e}")
    
    p = {
        "username": username,
        "displayName": disp,
        "hostname": clean_host,
        "idleTimeoutMinutes": timeout_minutes
    }
    with open(PROFILE_PATH, "w") as f:
        json.dump(p, f, indent=2)
    return True

