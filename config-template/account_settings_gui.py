    def on_lock_clicked(self, widget):
        try:
            urllib.request.urlopen("http://127.0.0.1:3000/auth_lock")
            self.lbl_status.set_markup("<span color='#ffb900'>🔒 Comando de bloqueio enviado!</span>")
        except Exception as e:
            self.lbl_status.set_markup(f"<span color='#e81123'>Erro ao bloquear: {e}</span>")

    def on_save_clicked(self, widget):
        username = self.entry_user.get_text().strip()
        display_name = self.entry_disp.get_text().strip()
        hostname = self.entry_host.get_text().strip()
        new_pass = self.entry_pass.get_text()
        confirm_pass = self.entry_confirm.get_text()

        if not username:
            self.lbl_status.set_markup("<span color='#e81123'>O nome de usuário não pode ficar vazio.</span>")
            return

        if not hostname:
            hostname = "cloud-vps"

        if new_pass:
            if new_pass != confirm_pass:
                self.lbl_status.set_markup("<span color='#e81123'>As senhas digitadas não coincidem.</span>")
                return
            if len(new_pass) < 4:
                self.lbl_status.set_markup("<span color='#e81123'>A senha deve ter no mínimo 4 caracteres.</span>")
                return

        idx = self.combo_timeout.get_active()
        timeout_val = self.timeout_options[idx][0] if idx >= 0 else 15

        try:
            save_credentials(username, new_pass if new_pass else None, display_name, timeout_val, hostname)
            self.lbl_title.set_text(display_name or username)
            self.lbl_subtitle.set_text(f"Conta Local • {username} ({hostname})")
            self.entry_pass.set_text("")
            self.entry_confirm.set_text("")
            self.lbl_status.set_markup("<span color='#107c41'><b>✓ Configurações salvas com sucesso!</b></span>")
        except Exception as e:
            self.lbl_status.set_markup(f"<span color='#e81123'>Erro ao salvar: {e}</span>")

